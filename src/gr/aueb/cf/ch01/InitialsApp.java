package gr.aueb.cf.ch01;

/**
 * Τυπώνει με * τα αρχικά ενός ονόματος.
 */
public class InitialsApp {

    public static void main(String[] args) {

        // Εκτύπωση
        System.out.println("*      *    *");
        System.out.println("**    **    * *");
        System.out.println("* *  * *    *   *");
        System.out.println("*  **  *    * * * *");
        System.out.println("*      *    *");
        System.out.println("*      *    *");
        System.out.println("*      *    *");

        /*
        Με την χρήση """ στην αρχή και στο τέλος ενός println,
        μπορούμε να γράψουμε πολλές γραμμές κώδικα με μόνο ένα println.
         */
    }
}
